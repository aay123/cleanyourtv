package com.cleanyourtv.mobile.data

import android.content.Context
import android.net.Uri
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

/**
 * Every run writes its record before the first change reaches the TV, and the restore button replays
 * that record. The record holds the state each package had before the run, the Home component, the
 * animation scales and (when used) the Private DNS values, so undo means undo.
 */
class BackupStore(private val context: Context) {

    private val dir: File get() = File(context.filesDir, "backups").apply { mkdirs() }

    fun save(record: BackupRecord) {
        val file = File(dir, "${record.id}.json")
        val temp = File(dir, "${record.id}.json.tmp")
        temp.writeText(recordToJson(record).toString(2), Charsets.UTF_8)
        try {
            java.nio.file.Files.move(
                temp.toPath(),
                file.toPath(),
                java.nio.file.StandardCopyOption.REPLACE_EXISTING,
                java.nio.file.StandardCopyOption.ATOMIC_MOVE,
            )
        } catch (error: java.nio.file.AtomicMoveNotSupportedException) {
            java.nio.file.Files.move(
                temp.toPath(),
                file.toPath(),
                java.nio.file.StandardCopyOption.REPLACE_EXISTING,
            )
        }
    }

    fun list(): List<BackupRecord> = dir.listFiles { file -> file.isFile && file.name.endsWith(".json") }
        ?.mapNotNull { file -> runCatching { jsonToRecord(JSONObject(file.readText(Charsets.UTF_8))) }.getOrNull() }
        ?.sortedByDescending { it.createdAt }
        ?: emptyList()

    fun load(id: String): BackupRecord? =
        File(dir, "$id.json").takeIf { it.isFile }?.let { file ->
            runCatching { jsonToRecord(JSONObject(file.readText(Charsets.UTF_8))) }.getOrNull()
        }

    fun export(uri: Uri, record: BackupRecord, listText: String, installed: List<String>) {
        val output = context.contentResolver.openOutputStream(uri)
            ?: throw IllegalStateException("cannot open the chosen file")
        ZipOutputStream(output.buffered()).use { zip ->
            zip.putText("backup.json", recordToJson(record).toString(2))
            zip.putText("debloat.txt", listText)
            zip.putText("installed-before.txt", installed.joinToString("\n"))
            zip.putText("disabled-before.txt", record.disabledBefore.joinToString("\n"))
            zip.putText("restore.sh", restoreScript(record))
            zip.putText("README.txt", EXPORT_README)
        }
    }

    private fun ZipOutputStream.putText(name: String, text: String) {
        putNextEntry(ZipEntry(name))
        write(text.toByteArray(Charsets.UTF_8))
        closeEntry()
    }

    private fun restoreScript(record: BackupRecord): String = buildString {
        appendLine("#!/usr/bin/env bash")
        appendLine("# Generated by the Clean Your TV phone app on ${record.createdAt}.")
        appendLine("# Re-enables every package that was enabled before the run; packages that were already")
        appendLine("# disabled stay disabled. Re-enabling an enabled package is a no-op.")
        appendLine("# Connect adb to the TV first (one device), then run this script.")
        appendLine("set -u")
        val enabledBefore = record.targetStates.filterValues { it == "enabled" }.keys
        for (packageName in (record.applied + enabledBefore).distinct()) {
            appendLine("adb shell pm enable ${shellQuote(packageName)}")
        }
        record.homeComponent?.let {
            appendLine("adb shell cmd package set-home-activity ${shellQuote(it)}")
        }
        for ((key, value) in record.animationScales) {
            appendLine("adb shell settings put global $key ${shellQuote(value)}")
        }
        if (record.dnsApplied) {
            appendLine("adb shell settings put global private_dns_mode ${shellQuote(record.dnsMode ?: "opportunistic")}")
            if (record.dnsSpecifier.isNullOrBlank()) {
                appendLine("adb shell settings delete global private_dns_specifier")
            } else {
                appendLine("adb shell settings put global private_dns_specifier ${shellQuote(record.dnsSpecifier)}")
            }
        }
        appendLine("adb shell pm list packages -d")
    }

    private fun shellQuote(value: String): String = "'" + value.replace("'", "'\\''") + "'"

    private fun recordToJson(record: BackupRecord): JSONObject = JSONObject().apply {
        put("version", 1)
        put("id", record.id)
        put("createdAt", record.createdAt)
        put("host", record.host)
        put("port", record.port)
        put("listId", record.listId)
        put("listTitle", record.listTitle)
        put("device", JSONObject().apply {
            put("model", record.device.model)
            put("brand", record.device.brand)
            put("manufacturer", record.device.manufacturer)
            put("device", record.device.device)
            put("product", record.device.product)
            put("name", record.device.name)
            put("androidVersion", record.device.androidVersion)
            put("sdk", record.device.sdk)
        })
        put("installed", JSONArray(record.installed))
        put("disabledBefore", JSONArray(record.disabledBefore))
        put("targetStates", JSONObject(record.targetStates))
        put("homeComponent", record.homeComponent ?: JSONObject.NULL)
        put("animationScales", JSONObject(record.animationScales))
        put("launcherPackage", record.launcherPackage ?: JSONObject.NULL)
        put("launcherApkName", record.launcherApkName ?: JSONObject.NULL)
        put("dnsMode", record.dnsMode ?: JSONObject.NULL)
        put("dnsSpecifier", record.dnsSpecifier ?: JSONObject.NULL)
        put("dnsApplied", record.dnsApplied)
        put("applied", JSONArray(record.applied))
        put("failed", JSONObject(record.failed))
        put("finished", record.finished)
    }

    private fun jsonToRecord(root: JSONObject): BackupRecord {
        val deviceJson = root.optJSONObject("device") ?: JSONObject()
        fun stringList(name: String): List<String> {
            val array = root.optJSONArray(name) ?: return emptyList()
            return (0 until array.length()).mapNotNull { array.optString(it).takeIf(String::isNotBlank) }
        }
        fun stringMap(name: String): Map<String, String> {
            val json = root.optJSONObject(name) ?: return emptyMap()
            val result = LinkedHashMap<String, String>()
            for (key in json.keys()) result[key] = json.optString(key)
            return result
        }
        fun nullableString(name: String): String? =
            if (root.isNull(name)) null else root.optString(name).takeIf { it.isNotBlank() }

        return BackupRecord(
            id = root.optString("id"),
            createdAt = root.optLong("createdAt"),
            host = root.optString("host"),
            port = root.optInt("port", 5555),
            device = DeviceInfo(
                model = deviceJson.optString("model"),
                brand = deviceJson.optString("brand"),
                manufacturer = deviceJson.optString("manufacturer"),
                device = deviceJson.optString("device"),
                product = deviceJson.optString("product"),
                name = deviceJson.optString("name"),
                androidVersion = deviceJson.optString("androidVersion"),
                sdk = deviceJson.optInt("sdk"),
            ),
            listId = root.optString("listId"),
            listTitle = root.optString("listTitle"),
            installed = stringList("installed"),
            disabledBefore = stringList("disabledBefore"),
            targetStates = stringMap("targetStates"),
            homeComponent = nullableString("homeComponent"),
            animationScales = stringMap("animationScales"),
            launcherPackage = nullableString("launcherPackage"),
            launcherApkName = nullableString("launcherApkName"),
            dnsMode = nullableString("dnsMode"),
            dnsSpecifier = nullableString("dnsSpecifier"),
            dnsApplied = root.optBoolean("dnsApplied"),
            applied = stringList("applied"),
            failed = stringMap("failed"),
            finished = root.optBoolean("finished"),
        )
    }

    companion object {
        private val EXPORT_README = """
            Clean Your TV phone app backup
            ==============================

            backup.json            The record the app's Restore button uses. Keep it.
            debloat.txt            The list this run applied.
            installed-before.txt   Every package installed before the run.
            disabled-before.txt    Packages that were already disabled before the run.
            restore.sh             Re-enables what this run disabled, with adb on a computer.

            Nothing was uninstalled. A package that was already disabled before the run is left
            disabled by restore, because that was its state when the record was written.
        """.trimIndent()
    }
}
